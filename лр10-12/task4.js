/* =======================================================================
   ЗАДАЧА 4. Работа с объектом Math  (Внешний файл — по условию задания)
   Расчёт по формуле:
            3 + (x - 1)^2
       y = ----------------
             a - cos(x)

   Требования:
   1. Организовать расчёт по формуле.
   2. Разработать пользовательскую функцию.
   3. Передачу результатов расчёта оформить через оператор return.
   4. Результаты расчётов отобразить в теле html-документа.
   ======================================================================= */

/**
 * Пользовательская функция для расчёта значения y.
 * @param {number} x - аргумент x
 * @param {number} a - параметр a
 * @returns {number|string} - результат расчёта или сообщение об ошибке
 */
function calcY(x, a) {
    // Проверка деления на ноль: знаменатель не должен быть равен нулю
    var denominator = a - Math.cos(x);
    if (denominator === 0) {
        return "Ошибка: деление на ноль (a - cos(x) = 0)";
    }

    // Числитель: 3 + (x - 1)^2
    var numerator = 3 + Math.pow(x - 1, 2);

    // Итоговый расчёт
    var y = numerator / denominator;

    // Передача результата через оператор return
    return y;
}

/**
 * Обработчик нажатия кнопки: получает значения x и a,
 * вызывает функцию calcY и выводит результат в тело документа.
 */
function calculateFormula() {
    // Получаем значения из полей ввода
    var x = parseFloat(document.getElementById("inputX").value);
    var a = parseFloat(document.getElementById("inputA").value);

    // Проверка корректности введённых данных
    if (isNaN(x) || isNaN(a)) {
        document.getElementById("out4").textContent =
            "Пожалуйста, введите числовые значения для x и a.";
        return;
    }

    // Вызов пользовательской функции (результат через return)
    var result = calcY(x, a);

    // Отображение результатов в теле html-документа
    var html =
        "Исходные данные:\n" +
        "  x = " + x + "\n" +
        "  a = " + a + "\n" +
        "-----------------------------------\n" +
        "Формула: y = (3 + (x - 1)^2) / (a - cos(x))\n" +
        "-----------------------------------\n" +
        "Результат: y = " + result;

    document.getElementById("out4").textContent = html;
}
