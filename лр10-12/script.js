/* -----------------------------------------------------------------------
   ЗАДАЧА 5. Работа со строками STRING
   S1 = имя, S2 = адрес.
   1. Определить длину строки S2.
   2. Сцепление строк S1 и S2.
   3. Преобразовать S1 в верхний регистр.
   Способ внедрения — внешний скрипт (этот файл).
   ----------------------------------------------------------------------- */
function processStrings() {
    var S1 = "Маргарита";
    var S2 = "г. Гродно, ул. Курчатова, 45";

    var lenS2 = S2.length;
    var concat = S1 + ", " + S2;
    var S1Upper = S1.toUpperCase();

    var html =
        "S1 = \"" + S1 + "\"\n" +
        "S2 = \"" + S2 + "\"\n" +
        "-----------------------------------\n" +
        "1. Длина строки S2 = " + lenS2 + "\n" +
        "2. Сцепление S1 и S2 = \"" + concat + "\"\n" +
        "3. S1 в верхнем регистр = \"" + S1Upper + "\"";

    document.getElementById("out5").textContent = html;
}